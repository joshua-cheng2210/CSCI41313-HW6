let slideshowTimer;
let currentSlideIndex = 0;

function startSlideshow() {
    const scheduleImage = document.getElementById('schedule-image');
    slideshowTimer = setInterval(() => {
        scheduleImage.classList.add('fade-out');
        setTimeout(() => {
            // iterating through the list of pictures in my DB
            currentSlideIndex = currentSlideIndex + 1;
            if (currentSlideIndex >= myscheduleDB.length){
                currentSlideIndex = currentSlideIndex % myscheduleDB.length
            } 
            const nextImage = myscheduleDB[currentSlideIndex]["data-thumbnail"];
            const nextAlt = myscheduleDB[currentSlideIndex]["data-thumbnail-alt"];
            scheduleImage.src = nextImage;
            scheduleImage.alt = nextAlt;
            scheduleImage.classList.remove('fade-out');
            scheduleImage.classList.add('fade-in');
            setTimeout(() => { // resetting the fading animation
                scheduleImage.classList.remove('fade-in');
            }, 500);
        }, 500);
    }, 5000);
}

function stopSlideshow() {
    clearInterval(slideshowTimer);
}

async function deleteSchedule(id, buttonElement) {
    try {
        const response = await fetch(`/deleteSchedule/${id}`, { 
            method: 'DELETE',
        });

        if (!response.ok){
            alert("failed to delete")
        } else {
            buttonElement.closest('tr').remove(); 
        }
    } catch (err) {
        throw err
    }
}

async function editSchedule(id) {
    console.log("client edit schedule: ", id)
    const editUrl = `/editSchedule/${id}`;
    window.location.href = editUrl; // this is a get function but from the browser
}

async function populateScheduleTable() {
    const tableBody = document.querySelector('.schedule-table tbody');

    try {
        const response = await fetch('/getSchedule'); 

        if (!response.ok) {
            throw new Error(`Failed to get Schedule. status -->${response.status}`);
        }
        
        let schedules = await response.json(); 
        schedules = schedules.results
        
        console.log("response from front end: ", schedules)

        schedules.forEach(schedule => {
            const row = document.createElement('tr');
            row.classList.add('schedule-row');

            row.innerHTML = `
                <td>${schedule.day || 'N/A'}</td>
                <td>${schedule.event || 'N/A'}</td>
                <td>${schedule.start} - ${schedule.end}</td>
                <td>${schedule.location || 'N/A'}</td>
                <td>${schedule.phone || 'N/A'}</td>
                <td><a href="${schedule.url || '#'}" target="_blank">${schedule.event || 'Info'}</a></td>
                <td>
                    <button class="edit-button" onclick="editSchedule(${schedule.id}, this)">Edit</button>
                    <button class="delete-button" onclick="deleteSchedule(${schedule.id}, this)">Delete</button>
                </td>
            `;
            tableBody.appendChild(row);
        });

    } catch (err) {
        throw err
    }
}
document.addEventListener('DOMContentLoaded', () => {
    populateScheduleTable()
});